import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';
import { marked } from 'marked';

// No browser or server is launched: exercise the production renderer in a DOM.
const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost:8080', runScripts: 'outside-only' });
for (const key of ['window', 'document', 'Node', 'Element', 'HTMLElement', 'DOMParser', 'NodeFilter']) globalThis[key] = dom.window[key];
dom.window.marked = marked;
dom.window.eval(readFileSync('public/vendor/katex/katex.min.js', 'utf8'));
dom.window.eval(readFileSync('public/vendor/katex/auto-render.min.js', 'utf8'));
const compiled = await build({ entryPoints: ['src/lib/markdown.ts'], bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', define: { 'import.meta.env.PROD': 'false' } });
const renderer = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const source = '# Reader\n\n## Method\n\nInline $x_1^2$ and display:\n\n$$\\frac{a}{b}$$\n\n![Figure](/vault/papers/example/images/图1.png)\n\n<script>window.compromised=true</script><img src="x" onerror="window.compromised=true"><a href="javascript:alert(1)">Bad link</a>\n\n<a data-ref="1" class="paper-cite">[1]</a>\n\n| A | B |\n|---|---|\n| 1 | 2 |';
const result = renderer.renderMarkdown(source);
const root = document.createElement('div'); root.innerHTML = result.html;
assert.equal(root.querySelector('script'), null, 'script must be removed');
assert.equal(root.querySelector('[onerror]'), null, 'event handler must be removed');
assert.equal(root.querySelector('a[href^="javascript:"]'), null, 'JavaScript URL must be removed');
assert.ok([...root.querySelectorAll('img')].some((img) => decodeURIComponent(img.getAttribute('src') || '') === '/vault/papers/example/images/图1.png'), 'image path must survive');
assert.ok(root.querySelector('a[data-ref="1"]'), 'reference attributes must survive');
assert.ok(root.querySelector('table'), 'editable table must survive');
assert.ok(result.headings.length > 0, 'table of contents must survive');
renderer.typesetMath(root);
assert.equal(root.querySelectorAll('.katex').length, 2, 'inline and display formulas must render');
assert.ok(root.textContent.includes('a') && root.textContent.includes('b'), 'formula variables must survive');
assert.equal(dom.window.compromised, undefined, 'untrusted content must not execute');
dom.window.close();
process.stdout.write('Markdown security and content checks passed (10 assertions).\n');
